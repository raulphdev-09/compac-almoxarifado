"""Additive, checksummed migrations shared by SQLite and PostgreSQL."""
import hashlib
import re
from datetime import datetime, timezone


BASE_REVISION = '001_security_integrity'
BASE_SQL = '''
CREATE TABLE IF NOT EXISTS idempotency_requests(
 user_id INTEGER NOT NULL REFERENCES users(id),
 scope TEXT NOT NULL,
 idempotency_key TEXT NOT NULL,
 request_hash TEXT NOT NULL,
 response_json TEXT NOT NULL,
 created_at TEXT NOT NULL,
 PRIMARY KEY(user_id,scope,idempotency_key)
);
CREATE TABLE IF NOT EXISTS auth_attempts(
 id INTEGER PRIMARY KEY,
 account_hash TEXT NOT NULL,
 origin_hash TEXT NOT NULL,
 attempted_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS auth_attempts_account_time ON auth_attempts(account_hash,attempted_at);
CREATE INDEX IF NOT EXISTS auth_attempts_origin_time ON auth_attempts(origin_hash,attempted_at);
CREATE INDEX IF NOT EXISTS auth_attempts_time ON auth_attempts(attempted_at);
'''
BASE_CHECKSUM = hashlib.sha256(BASE_SQL.encode()).hexdigest()
REVISION = '002_attendance_experimental'
SQL = '''
CREATE TABLE IF NOT EXISTS attendance_terminals(
 id INTEGER PRIMARY KEY,
 name TEXT NOT NULL,
 work_id INTEGER NOT NULL REFERENCES works(id),
 active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)),
 created_by INTEGER NOT NULL REFERENCES users(id),
 created_at TEXT NOT NULL,
 revoked_at TEXT
);
CREATE TABLE IF NOT EXISTS attendance_authorizations(
 token_hash TEXT NOT NULL PRIMARY KEY,
 employee_id INTEGER NOT NULL REFERENCES employees(id),
 terminal_id INTEGER NOT NULL REFERENCES attendance_terminals(id),
 created_by INTEGER NOT NULL REFERENCES users(id),
 created_at TEXT NOT NULL,
 expires_at TEXT NOT NULL,
 used_at TEXT
);
CREATE TABLE IF NOT EXISTS attendance_records(
 id INTEGER PRIMARY KEY,
 record_uid TEXT NOT NULL UNIQUE,
 employee_id INTEGER NOT NULL REFERENCES employees(id),
 work_id INTEGER NOT NULL REFERENCES works(id),
 terminal_id INTEGER NOT NULL REFERENCES attendance_terminals(id),
 mark_type TEXT NOT NULL CHECK(mark_type IN ('ENTRADA','INICIO_INTERVALO','RETORNO_INTERVALO','SAIDA')),
 marked_at TEXT NOT NULL,
 verification_method TEXT NOT NULL CHECK(verification_method='DEMO_SUPERVISIONADO'),
 verification_result TEXT NOT NULL CHECK(verification_result='SIMULADO'),
 is_test INTEGER NOT NULL CHECK(is_test=1),
 created_by INTEGER NOT NULL REFERENCES users(id),
 authorization_hash TEXT NOT NULL UNIQUE REFERENCES attendance_authorizations(token_hash)
);
CREATE INDEX IF NOT EXISTS attendance_records_employee_time ON attendance_records(employee_id,marked_at,id);
CREATE INDEX IF NOT EXISTS attendance_records_work_time ON attendance_records(work_id,marked_at,id);
CREATE INDEX IF NOT EXISTS attendance_authorizations_expiry ON attendance_authorizations(expires_at);
'''
CHECKSUM = hashlib.sha256(SQL.encode()).hexdigest()
MIGRATIONS = ((BASE_REVISION, BASE_SQL), (REVISION, SQL))
CHECKSUMS = {version: hashlib.sha256(source.encode()).hexdigest() for version, source in MIGRATIONS}
BASE_EXPECTED = {
    'idempotency_requests': (('user_id', 'scope', 'idempotency_key', 'request_hash', 'response_json', 'created_at'), ('user_id', 'scope', 'idempotency_key')),
    'auth_attempts': (('id', 'account_hash', 'origin_hash', 'attempted_at'), ('id',)),
}
ATTENDANCE_EXPECTED = {
    'attendance_terminals': (('id', 'name', 'work_id', 'active', 'created_by', 'created_at', 'revoked_at'), ('id',)),
    'attendance_authorizations': (('token_hash', 'employee_id', 'terminal_id', 'created_by', 'created_at', 'expires_at', 'used_at'), ('token_hash',)),
    'attendance_records': (('id', 'record_uid', 'employee_id', 'work_id', 'terminal_id', 'mark_type', 'marked_at', 'verification_method', 'verification_result', 'is_test', 'created_by', 'authorization_hash'), ('id',)),
}
EXPECTED = {**BASE_EXPECTED, **ATTENDANCE_EXPECTED}
BASE_INDEXES = {'auth_attempts_account_time', 'auth_attempts_origin_time', 'auth_attempts_time'}
ATTENDANCE_INDEXES = {'attendance_records_employee_time', 'attendance_records_work_time', 'attendance_authorizations_expiry'}


def table_exists(db, name):
    if db.postgres:
        return bool(db.execute('SELECT 1 FROM information_schema.tables WHERE table_schema=current_schema() AND table_name=?', (name,)).fetchone())
    return bool(db.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (name,)).fetchone())


def statements(db, source=None):
    source = SQL if source is None else source
    if db.postgres:
        source = source.replace('id INTEGER PRIMARY KEY', 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        source = re.sub(r'\bINTEGER\b', 'BIGINT', source)
    return [statement.strip() for statement in source.split(';') if statement.strip()]


def applied_revisions(db):
    if not table_exists(db, 'schema_migrations'):
        return {}
    applied = {row['version']: row['checksum'] for row in db.execute('SELECT version,checksum FROM schema_migrations')}
    if set(applied) - set(CHECKSUMS):
        raise RuntimeError('Revisão de migração desconhecida; interrompido para revisão.')
    gap = False
    for version, _ in MIGRATIONS:
        if version not in applied:
            gap = True
        elif gap:
            raise RuntimeError('Sequência de migrações incompleta; interrompido para revisão.')
    return applied


def status(db):
    applied = applied_revisions(db)
    valid = all(checksum == CHECKSUMS[version] for version, checksum in applied.items())
    complete = REVISION in applied
    return {'revision': REVISION, 'applied': complete, 'checksum_valid': valid if complete or not valid else None}


def _validate_tables(db, expected):
    for name, (required, primary) in expected.items():
        if not table_exists(db, name):
            raise RuntimeError('Schema incompleto para a migração registrada; restaure ou revise o banco.')
        if db.postgres:
            columns = {r['column_name'] for r in db.execute('SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=?', (name,))}
            keys = tuple(r['column_name'] for r in db.execute("SELECT k.column_name FROM information_schema.table_constraints c JOIN information_schema.key_column_usage k ON c.constraint_name=k.constraint_name AND c.constraint_schema=k.constraint_schema AND c.table_name=k.table_name WHERE c.table_schema=current_schema() AND c.table_name=? AND c.constraint_type='PRIMARY KEY' ORDER BY k.ordinal_position", (name,)))
        else:
            info = db.execute(f'PRAGMA table_info({name})').fetchall()
            columns = {r['name'] for r in info}
            keys = tuple(r['name'] for r in sorted(info, key=lambda r: r['pk']) if r['pk'])
        if not set(required) <= columns or keys != primary:
            raise RuntimeError('Schema incompleto ou chave divergente; interrompido para revisão.')


def _indexes(db, names):
    if db.postgres:
        return {r['indexname'] for r in db.execute('SELECT indexname FROM pg_indexes WHERE schemaname=current_schema()')}
    return {r['name'] for name in names for r in db.execute(f'PRAGMA index_list({name})')}


def _unique_columns(db, table):
    if db.postgres:
        rows = db.execute("SELECT c.constraint_name,k.column_name FROM information_schema.table_constraints c JOIN information_schema.key_column_usage k ON c.constraint_name=k.constraint_name AND c.constraint_schema=k.constraint_schema AND c.table_name=k.table_name WHERE c.table_schema=current_schema() AND c.table_name=? AND c.constraint_type='UNIQUE' ORDER BY c.constraint_name,k.ordinal_position", (table,)).fetchall()
        grouped = {}
        for row in rows:
            grouped.setdefault(row['constraint_name'], []).append(row['column_name'])
        return {tuple(columns) for columns in grouped.values()}
    unique = set()
    for index in db.execute(f'PRAGMA index_list({table})'):
        if index['unique']:
            name = index['name'].replace('"', '""')
            unique.add(tuple(row['name'] for row in db.execute(f'PRAGMA index_info("{name}")')))
    return unique


def validate_structure(db, *, through=REVISION):
    _validate_tables(db, BASE_EXPECTED)
    if not BASE_INDEXES <= _indexes(db, BASE_EXPECTED):
        raise RuntimeError('Schema incompleto: índices de autenticação ausentes.')
    if through == BASE_REVISION:
        return
    _validate_tables(db, ATTENDANCE_EXPECTED)
    if not ATTENDANCE_INDEXES <= _indexes(db, ATTENDANCE_EXPECTED):
        raise RuntimeError('Schema incompleto: índices de ponto ausentes.')
    if not {('record_uid',), ('authorization_hash',)} <= _unique_columns(db, 'attendance_records'):
        raise RuntimeError('Schema incompleto: unicidade dos registros de ponto ausente.')


def migrate(db, *, allow_apply):
    applied = applied_revisions(db)
    if any(checksum != CHECKSUMS[version] for version, checksum in applied.items()):
        raise RuntimeError('Checksum de migração divergente; interrompido para revisão.')
    for version, _ in MIGRATIONS:
        if version in applied:
            validate_structure(db, through=version)
    if REVISION in applied:
        return
    if not allow_apply:
        raise RuntimeError('Migração pendente. Após backup e autorização, execute python -m app.migrate --apply.')
    db.execute('CREATE TABLE IF NOT EXISTS schema_migrations(version TEXT PRIMARY KEY,checksum TEXT NOT NULL,applied_at TEXT NOT NULL)')
    # Each revision and its version record share the caller's transaction.
    # sqlite3.executescript is deliberately avoided: it can commit implicitly.
    for version, source in MIGRATIONS:
        if version in applied:
            continue
        for statement in statements(db, source):
            db.execute(statement)
        validate_structure(db, through=version)
        db.execute('INSERT INTO schema_migrations(version,checksum,applied_at) VALUES(?,?,?)',
                   (version, CHECKSUMS[version], datetime.now(timezone.utc).isoformat()))
