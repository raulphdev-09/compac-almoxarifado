"""Additive, checksummed migrations shared by SQLite and PostgreSQL."""
import hashlib
import re
from datetime import datetime, timezone


REVISION = '001_security_integrity'
SQL = '''
CREATE TABLE IF NOT EXISTS idempotency_requests(
 user_id INTEGER NOT NULL REFERENCES users(id),
 scope TEXT NOT NULL,
 idempotency_key TEXT NOT NULL,
 request_hash TEXT NOT NULL,
 response_json TEXT NOT NULL,
 created_at TEXT NOT NULL,
 PRIMARY KEY(user_id,scope,idempotency_key)
);
CREATE TABLE IF NOT EXISTS auth_attempts(
 id INTEGER PRIMARY KEY,
 account_hash TEXT NOT NULL,
 origin_hash TEXT NOT NULL,
 attempted_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS auth_attempts_account_time ON auth_attempts(account_hash,attempted_at);
CREATE INDEX IF NOT EXISTS auth_attempts_origin_time ON auth_attempts(origin_hash,attempted_at);
CREATE INDEX IF NOT EXISTS auth_attempts_time ON auth_attempts(attempted_at);
'''
CHECKSUM = hashlib.sha256(SQL.encode()).hexdigest()
EXPECTED = {
    'idempotency_requests': (('user_id', 'scope', 'idempotency_key', 'request_hash', 'response_json', 'created_at'), ('user_id', 'scope', 'idempotency_key')),
    'auth_attempts': (('id', 'account_hash', 'origin_hash', 'attempted_at'), ('id',)),
}


def table_exists(db, name):
    if db.postgres:
        return bool(db.execute('SELECT 1 FROM information_schema.tables WHERE table_schema=current_schema() AND table_name=?', (name,)).fetchone())
    return bool(db.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (name,)).fetchone())


def statements(db):
    sql = SQL
    if db.postgres:
        sql = sql.replace('id INTEGER PRIMARY KEY', 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        sql = re.sub(r'\bINTEGER\b', 'BIGINT', sql)
    return [statement.strip() for statement in sql.split(';') if statement.strip()]


def status(db):
    if not table_exists(db, 'schema_migrations'):
        return {'revision': REVISION, 'applied': False, 'checksum_valid': None}
    row = db.execute('SELECT checksum FROM schema_migrations WHERE version=?', (REVISION,)).fetchone()
    return {'revision': REVISION, 'applied': bool(row), 'checksum_valid': row['checksum'] == CHECKSUM if row else None}


def validate_structure(db):
    for name, (required, primary) in EXPECTED.items():
        if not table_exists(db, name):
            raise RuntimeError('Schema incompleto para a migração registrada; restaure ou revise o banco.')
        if db.postgres:
            columns = {r['column_name'] for r in db.execute('SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=?', (name,))}
            keys = tuple(r['column_name'] for r in db.execute("SELECT k.column_name FROM information_schema.table_constraints c JOIN information_schema.key_column_usage k ON c.constraint_name=k.constraint_name AND c.constraint_schema=k.constraint_schema AND c.table_name=k.table_name WHERE c.table_schema=current_schema() AND c.table_name=? AND c.constraint_type='PRIMARY KEY' ORDER BY k.ordinal_position", (name,)))
        else:
            info = db.execute(f'PRAGMA table_info({name})').fetchall()
            columns = {r['name'] for r in info}
            keys = tuple(r['name'] for r in sorted(info, key=lambda r: r['pk']) if r['pk'])
        if not set(required) <= columns or keys != primary:
            raise RuntimeError('Schema incompleto ou chave divergente; interrompido para revisão.')
    if db.postgres:
        indexes = {r['indexname'] for r in db.execute("SELECT indexname FROM pg_indexes WHERE schemaname=current_schema() AND tablename='auth_attempts'")}
    else:
        indexes = {r['name'] for r in db.execute('PRAGMA index_list(auth_attempts)')}
    if not {'auth_attempts_account_time', 'auth_attempts_origin_time', 'auth_attempts_time'} <= indexes:
        raise RuntimeError('Schema incompleto: índices de autenticação ausentes.')


def migrate(db, *, allow_apply):
    state = status(db)
    if state['applied']:
        if not state['checksum_valid']:
            raise RuntimeError('Checksum de migração divergente; interrompido para revisão.')
        validate_structure(db)
        return
    if not allow_apply:
        raise RuntimeError('Migração pendente. Após backup e autorização, execute python -m app.migrate --apply.')
    db.execute('CREATE TABLE IF NOT EXISTS schema_migrations(version TEXT PRIMARY KEY,checksum TEXT NOT NULL,applied_at TEXT NOT NULL)')
    # Execute separately: sqlite3.executescript can commit an outer transaction.
    for statement in statements(db):
        db.execute(statement)
    validate_structure(db)
    db.execute('INSERT INTO schema_migrations(version,checksum,applied_at) VALUES(?,?,?)',
               (REVISION, CHECKSUM, datetime.now(timezone.utc).isoformat()))
